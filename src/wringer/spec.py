def render_rubric(spec: Spec) -> str:
    """The criteria block as a standalone `wringer.rubric.v1` file.

    No translation layer: the same criteria, the same keys, the same parser.
    """
    document: dict[str, Any] = {
        "schema_version": "wringer.rubric.v1",
        "title": spec.title,
        "criteria": [
            {
                "id": c.id,
                "title": c.title,
                **({"guidance": c.guidance} if c.guidance else {}),
                "required": c.required,
                "human": c.human,
            }
            for c in spec.criteria
        ],
    }
    return yaml.safe_dump(document, sort_keys=False, allow_unicode=True)


def validate_rubric_text(text: str) -> None:
    """Prove a rendered rubric is one, before it is written.

    Runs the judge's own parser and the judge's own size limit. If this passes,
    `rubric.load` on the written file cannot fail — which is what "the criteria
    block is a rubric by construction" has to mean to be worth saying.
    """
    encoded = len(text.encode("utf-8"))
    if encoded > MAX_RUBRIC_BYTES:
        raise SpecError(
            f"the criteria render to {encoded} bytes, over the "
            f"{MAX_RUBRIC_BYTES}-byte rubric limit — these bytes travel"
        )
    try:
        parse_document(yaml.safe_load(text), RUBRIC_FILENAME)
    except (RubricError, yaml.YAMLError) as exc:
        raise SpecError(f"the criteria are not a usable rubric: {exc}") from exc


def render_brief(spec: Spec, task: Task) -> str:
    """One task's brief — a file, never an inline payload (invariant 5)."""
    lines = [
        BRIEF_MARKER,
        "",
        f"# {task.id} — {spec.title}",
        "",
        "## Objective",
        "",
        task.objective,
        "",
        "## Acceptance criteria",
        "",
        "These are what the change will be judged against.",
        "",
    ]
    for criterion in spec.criteria:
        tags = []
        if not criterion.required:
            tags.append("optional")
        if criterion.human:
            tags.append("a human scores this")
        suffix = f" _({', '.join(tags)})_" if tags else ""
        lines.append(f"- **{criterion.id}** — {criterion.title}{suffix}")
        if criterion.guidance:
            lines.append(f"  - {criterion.guidance}")

    answered = [q for q in spec.questions if q.answered]
    if answered:
        lines += ["", "## Decisions already made", ""]
        lines += [f"- **{q.question}** {q.answer}" for q in answered]

    lines += [
        "",
        "## What the product manager asked for",
        "",
        "```",
        spec.intent,
        "```",
        "",
    ]
    return "\n".join(lines)


def render_tasks(spec: Spec) -> str:
    """`tasks.jsonl`, exactly the shape `fleet.load_tasks` accepts."""
    return "".join(
        json.dumps({"id": t.id, "brief": t.brief, "dir": t.dir}) + "\n"
        for t in spec.tasks
    )


def gate_diff(existing: str, spec: Spec) -> tuple[str, tuple[str, ...],
                                                  tuple[str, ...]]:
    """The change a human would have to make to `.wringer.yaml`, as a diff.

    Returns the diff text, the ids it would add, and the ids that already
    exist. Wringer prints this and stops: installing a gate is changing what
    "verified" means, and that is not a thing a drafter gets to do quietly.
    """
    import difflib
    import re

    declared = set(re.findall(r"^\s*-\s*id:\s*([A-Za-z0-9][\w-]*)", existing,
                              re.MULTILINE))
    fresh = tuple(g.id for g in spec.gates if g.id not in declared)
    already = tuple(g.id for g in spec.gates if g.id in declared)
    if not fresh:
        return "", fresh, already

    addition = []
    for gate in spec.gates:
        if gate.id not in fresh:
            continue
        addition += [f"  - id: {gate.id}", f"    run: {_scalar(gate.run)}"]
        if gate.timeout != config.DEFAULT_TIMEOUT_SECONDS:
            addition.append(f"    timeout: {gate.timeout}")
        if gate.optional:
            addition.append("    optional: true")

    before = existing.splitlines(keepends=True)
    proposed = _append_gates(existing, addition).splitlines(keepends=True)
    # `a/` and `b/` so `git apply` accepts it as-is. The human is the intended
    # applier, but a diff a machine cannot apply is a diff nobody checked.
    diff = "".join(
        difflib.unified_diff(
            before,
            proposed,
            fromfile=f"a/{config.CONFIG_FILENAME}",
            tofile=f"b/{config.CONFIG_FILENAME}",
        )
    )
    return diff, fresh, already


def _append_gates(existing: str, addition: list[str]) -> str:
    """Put the new gates under the existing `gates:` key, or add the key.

    Textual on purpose: a round-trip through a YAML dumper would reformat a
    file the human wrote, and a diff full of unrelated reflowing is a diff
    nobody reads.
    """
    lines = existing.splitlines()
    block = "\n".join(addition)
    for index, line in enumerate(lines):
        if line.rstrip() != "gates:":
            continue
        end = index + 1
        while end < len(lines) and (
            not lines[end].strip() or lines[end].startswith((" ", "\t", "#"))
        ):
            end += 1
        return "\n".join(lines[:end] + addition + lines[end:]) + "\n"
    tail = "" if existing.endswith("\n") or not existing else "\n"
    return f"{existing}{tail}gates:\n{block}\n"


def tasks_file_is_generated(path: Path) -> bool:
    """Whether overwriting `tasks.jsonl` would destroy something else.

    There is no comment syntax in JSONL to leave a marker in, so the check is
    the real parser: a file every line of which is a task is a task file.
    """
    from wringer import fleet

    if not path.exists():
        return True
    try:
        fleet.load_tasks(path)
    except fleet.FleetError:
        return False
    return True


def brief_is_generated(path: Path) -> bool:
    if not path.exists():
        return True
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:200]
    except OSError:
        return False
    return BRIEF_MARKER in head


# --- the drafting bundle -------------------------------------------------


@dataclass(frozen=True)
class Bundle:
    """`.wringer/specs/<id>/`. Owns the redactor, so every write scrubs.

    The judge's shape, for the judge's reason: what would leave the machine is
    on disk before any socket opens, so it is auditable rather than asserted.
    """

    directory: Path
    spec_id: str
    started_at: datetime
    redactor: Redactor = Redactor()

    @classmethod
    def create(
        cls,
        specs_root: Path,
        now: datetime | None = None,
        redactor: Redactor | None = None,
    ) -> Bundle:
        started_at = now if now is not None else datetime.now().astimezone()
        try:
            specs_root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise SpecError(f"cannot create {specs_root}: {exc}") from exc
        for _ in range(64):
            spec_id = evidence.new_run_id(started_at)
            directory = specs_root / spec_id
            try:
                directory.mkdir(exist_ok=False)
            except FileExistsError:
                continue
            except OSError as exc:
                raise SpecError(f"cannot create {directory}: {exc}") from exc
            return cls(directory, spec_id, started_at, redactor or Redactor())
        raise SpecError(f"could not allocate a directory under {specs_root}")

    def write_request(self, request: dict) -> Path:
        path = self.directory / REQUEST_FILENAME
        scrubbed = evidence.deep_scrub(self.redactor, request)
        path.write_text(json.dumps(scrubbed, indent=2) + "\n", encoding="utf-8")
        return path

    def write_response(self, body: Any) -> Path:
        path = self.directory / RESPONSE_FILENAME
        scrubbed = evidence.deep_scrub(self.redactor, body)
        path.write_text(json.dumps(scrubbed, indent=2) + "\n", encoding="utf-8")
        return path

    def write_summary(
        self, mode: str, prd: str, endpoint: str, model: str, drafted: Spec | None
    ) -> Path:
        lines = [
            f"# wring spec — {self.spec_id}",
            "",
            f"- mode: **{mode}**",
            f"- PRD: `{prd}`",
            f"- endpoint: `{self.redactor.scrub(endpoint)}`",
            f"- model: {model}",
        ]
        if drafted is None:
            lines += [
                "",
                "Nothing was drafted: this was a dry run, so the request was "
                f"built and written to `{REQUEST_FILENAME}` and no socket was "
                "opened.",
            ]
        else:
            lines += [
                f"- drafted: `{SPEC_FILENAME}` — **approved: false**",
                "",
                f"| {len(drafted.criteria)} criteria "
                f"| {len(drafted.gates)} gates "
                f"| {len(drafted.tasks)} tasks "
                f"| {len(drafted.questions)} open questions |",
                "|---|---|---|---|",
                "",
                f"Read `{SPEC_FILENAME}`, answer its open questions, and set "
                "`approved: true` by hand. Then run `wring plan`.",
            ]
        path = self.directory / SUMMARY_FILENAME
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return path
