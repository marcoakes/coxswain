"""Prose in, testable criteria out — `wringer.spec.v1` (SPEC_INTENT_V0.md).

The front door. A product manager writes what they want in plain language;
`wring spec` drafts acceptance criteria, gates and a build plan **as a file on
disk**; a human reads and approves that file; `wring plan` compiles it into
work a fleet can run.

The failure mode this module exists to prevent is not a bad build — it is a
*confident build of the wrong thing*. Three defences, all structural, all
here rather than in the prompt:

1. **`approved` is never read from the model.** `draft()` writes
   `approved: false` unconditionally; there is no code path along which a
   reply, a flag or an environment variable can set it true. A human edits the
   file, which is why there is no `--yes`.
2. **`intent` is written from the PRD, not from the reply.** A model
   paraphrasing the human's own words inside the artifact the human is about
   to approve is the confident-wrong-answer in miniature, so Wringer quotes
   the source file and ignores whatever the model called it.
3. **Everything proposed is validated by the real parser.** Criteria go
   through `rubric.parse_document`, gates through `config.parse_gate`. Wringer
   cannot propose a rubric the judge would reject or a gate `.wringer.yaml`
   would refuse, because the same code decides both.

**This module opens no socket.** `wring spec --send` reuses `judge.send` — the
one function in Wringer that does — with the `judge:` section's endpoint,
model and key rules verbatim. One network config, one set of safety rules, one
auditable path (SPEC_INTENT_V0.md §2).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

import yaml

from wringer import config, evidence
from wringer.redact import Redactor
from wringer.rubric import (
    MAX_RUBRIC_BYTES,
    Criterion,
    RubricError,
    parse_document,
)

SCHEMA_VERSION = "wringer.spec.v1"
SPEC_FILENAME = "wringer.spec.yaml"
RUBRIC_FILENAME = "wringer.rubric.yaml"
TASKS_FILENAME = "tasks.jsonl"
SPECS_DIRNAME = Path(".wringer") / "specs"
REQUEST_FILENAME = "request.json"
RESPONSE_FILENAME = "response.json"
SUMMARY_FILENAME = "summary.md"

# A PRD is a page or two. These bytes travel to an endpoint, so they get the
# rubric's treatment: a declared ceiling rather than whatever the disk holds.
MAX_PRD_BYTES = 64 * 1024
# How much of the PRD is quoted verbatim into `intent`. The whole thing when
# it fits, which for a real PRD it does.
MAX_INTENT_CHARS = 8000
MAX_SPEC_BYTES = 128 * 1024
# A PRD that yields fifty tasks was not understood. The fleet can run hundreds;
# a single drafting pass proposing them is a sign to read the reply, not to
# start it.
MAX_TASKS = 50
MAX_OPEN_QUESTIONS = 20

# Every brief `wring plan` writes starts with this line, and `wring plan`
# refuses to overwrite a file that does not carry it. Briefs are generated
# from the spec on every run; a hand-written file that happened to share a
# name must not be silently replaced.
BRIEF_MARKER = (
    "<!-- generated by `wring plan` from wringer.spec.yaml — "
    "edits here are overwritten; edit the spec -->"
)

_TOP_LEVEL_KEYS = {
    "schema_version",
    "approved",
    "title",
    "intent",
    "open_questions",
    "criteria",
    "gates",
    "tasks",
}
_QUESTION_KEYS = {"id", "question", "required", "answer"}
_TASK_KEYS = {"id", "brief", "dir", "objective"}


class SpecError(Exception):
    """An unusable spec, PRD or reply (CLI exit code 2)."""


@dataclass(frozen=True)
class Question:
    id: str
    question: str
    required: bool = True
    answer: str = ""

    @property
    def answered(self) -> bool:
        """A question is answered when someone wrote an answer under it.

        Deleting the question works too — it is simply gone. Both are file
        edits, which is the only kind of approval this slice accepts.
        """
        return bool(self.answer.strip())


@dataclass(frozen=True)
class Task:
    id: str
    brief: str
    objective: str
    dir: str = "."


@dataclass(frozen=True)
class Spec:
    approved: bool
    title: str
    intent: str
    questions: tuple[Question, ...]
    criteria: tuple[Criterion, ...]
    gates: tuple[config.Gate, ...]
    tasks: tuple[Task, ...]
    path: str

    @property
    def unanswered(self) -> tuple[Question, ...]:
        return tuple(q for q in self.questions if q.required and not q.answered)


# --- reading a spec file -------------------------------------------------


def load(path: Path) -> Spec:
    """Read and validate `wringer.spec.yaml`.

    Re-read from disk on every `wring plan`, never cached and never carried
    over from the drafting run: `approved` means what the file says now.
    """
    if not path.is_file():
        raise SpecError(
            f"no {path.name} in {path.parent} — draft one with "
            f"'wring spec <PRD.md>'"
        )
    raw_bytes = path.read_bytes()
    if len(raw_bytes) > MAX_SPEC_BYTES:
        raise SpecError(
            f"{path.name} is {len(raw_bytes)} bytes, over the "
            f"{MAX_SPEC_BYTES}-byte limit"
        )
    try:
        data = yaml.safe_load(raw_bytes.decode("utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise SpecError(f"{path.name} is not valid YAML: {exc}") from exc
    return parse(data, path.name)


def parse(data: Any, where: str) -> Spec:
    """Validate a spec mapping — strict, like every other loader here."""
    if not isinstance(data, dict):
        raise SpecError(f"{where}: top level must be a mapping")

    unknown = sorted(set(data) - _TOP_LEVEL_KEYS)
    if unknown:
        raise SpecError(f"{where}: unknown keys: {', '.join(unknown)}")

    declared = data.get("schema_version")
    if declared != SCHEMA_VERSION:
        raise SpecError(
            f"{where}: 'schema_version: {SCHEMA_VERSION}' is required "
            f"(got {declared!r})"
        )

    approved = data.get("approved")
    if not isinstance(approved, bool):
        raise SpecError(
            f"{where}: 'approved' must be a boolean, and must be present — it "
            "is the interlock, so a spec that forgot to say is not approved by "
            "omission"
        )

    title = _nonempty(data.get("title"), f"{where}: 'title'")
    intent = _nonempty(data.get("intent"), f"{where}: 'intent'")

    questions = _parse_questions(data.get("open_questions"), where)

    criteria_raw = data.get("criteria")
    try:
        _, criteria = parse_document(
            {
                "schema_version": "wringer.rubric.v1",
                "title": title,
                "criteria": criteria_raw,
            },
            where,
        )
    except RubricError as exc:
        raise SpecError(str(exc)) from exc

    gates_raw = data.get("gates") or []
    if not isinstance(gates_raw, list):
        raise SpecError(f"{where}: 'gates' must be a list")
    try:
        gates = tuple(
            config.parse_gate(entry, index, where)
            for index, entry in enumerate(gates_raw)
        )
    except config.ConfigError as exc:
        raise SpecError(str(exc)) from exc
    seen: set[str] = set()
    for gate in gates:
        if gate.id in seen:
            raise SpecError(f"{where}: duplicate gate id '{gate.id}'")
        seen.add(gate.id)

    tasks = _parse_tasks(data.get("tasks"), where)

    return Spec(
        approved=approved,
        title=title,
        intent=intent,
        questions=questions,
        criteria=criteria,
        gates=gates,
        tasks=tasks,
        path=where,
    )


def _nonempty(value: Any, at: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise SpecError(f"{at} must be a non-empty string")
    return value


def _slug(value: Any, at: str) -> str:
    identifier = _nonempty(value, at)
    if len(identifier) > config.MAX_GATE_ID_LENGTH or not (
        config.GATE_ID_PATTERN.fullmatch(identifier)
    ):
        raise SpecError(
            f"{at} ('{identifier}') must be a slug — letters, digits, '-' and "
            "'_', starting with a letter or digit"
        )
    return identifier


def _parse_questions(raw: Any, where: str) -> tuple[Question, ...]:
    if raw is None:
        return ()
    if not isinstance(raw, list):
        raise SpecError(f"{where}: 'open_questions' must be a list")
    if len(raw) > MAX_OPEN_QUESTIONS:
        raise SpecError(
            f"{where}: {len(raw)} open questions, over the limit of "
            f"{MAX_OPEN_QUESTIONS} — a spec that unclear needs a conversation, "
            "not a form"
        )

    questions: list[Question] = []
    seen: set[str] = set()
    for index, entry in enumerate(raw):
        at = f"{where}: open_questions[{index}]"
        if not isinstance(entry, dict):
            raise SpecError(f"{at} must be a mapping")
        unknown = sorted(set(entry) - _QUESTION_KEYS)
        if unknown:
            raise SpecError(f"{at}: unknown keys: {', '.join(unknown)}")

        question_id = _slug(entry.get("id"), f"{at}: 'id'")
        if question_id in seen:
            raise SpecError(f"{at}: duplicate question id '{question_id}'")
        seen.add(question_id)

        required = entry.get("required", True)
        if not isinstance(required, bool):
            raise SpecError(f"{at} ('{question_id}'): 'required' must be a boolean")
        answer = entry.get("answer", "")
        if answer is None:
            answer = ""
        if not isinstance(answer, str):
            raise SpecError(f"{at} ('{question_id}'): 'answer' must be a string")

        questions.append(
            Question(
                id=question_id,
                question=_nonempty(entry.get("question"), f"{at}: 'question'"),
                required=required,
                answer=answer,
            )
        )
    return tuple(questions)


def _parse_tasks(raw: Any, where: str) -> tuple[Task, ...]:
    if not isinstance(raw, list) or not raw:
        raise SpecError(f"{where}: 'tasks' must be a non-empty list")
    if len(raw) > MAX_TASKS:
        raise SpecError(
            f"{where}: {len(raw)} tasks, over the limit of {MAX_TASKS} — a "
            "single drafting pass proposing that many was not understanding "
            "the PRD"
        )

    tasks: list[Task] = []
    seen: set[str] = set()
    for index, entry in enumerate(raw):
        at = f"{where}: tasks[{index}]"
        if not isinstance(entry, dict):
            raise SpecError(f"{at} must be a mapping")
        unknown = sorted(set(entry) - _TASK_KEYS)
        if unknown:
            raise SpecError(f"{at}: unknown keys: {', '.join(unknown)}")

        # The same slug rule as a fleet task id, because this becomes one.
        task_id = _slug(entry.get("id"), f"{at}: 'id'")
        if task_id in seen:
            raise SpecError(f"{at}: duplicate task id '{task_id}'")
        seen.add(task_id)

        brief = _nonempty(entry.get("brief"), f"{at} ('{task_id}'): 'brief'")
        _check_contained(brief, f"{at} ('{task_id}'): 'brief'")
        directory = entry.get("dir", ".")
        if not isinstance(directory, str) or not directory.strip():
            raise SpecError(f"{at} ('{task_id}'): 'dir' must be a non-empty string")
        _check_contained(directory, f"{at} ('{task_id}'): 'dir'")

        tasks.append(
            Task(
                id=task_id,
                brief=brief,
                objective=_nonempty(
                    entry.get("objective"), f"{at} ('{task_id}'): 'objective'"
                ),
                dir=directory,
            )
        )
    return tuple(tasks)


def _check_contained(candidate: str, at: str) -> None:
    """Refuse any path that could leave the repository.

    `wring plan` **writes** brief files at these paths, and the paths were
    proposed by a model. An absolute path or a `..` here is the difference
    between generating a document and overwriting `~/.ssh/config`. Checked on
    the string, before any filesystem call, so a symlink cannot answer for it.
    """
    path = Path(candidate)
    if path.is_absolute() or candidate.startswith("~"):
        raise SpecError(f"{at} must be a path relative to the repository root")
    if ".." in path.parts:
        raise SpecError(f"{at} must not escape the repository with '..'")


def resolve_inside(root: Path, candidate: str, at: str) -> Path:
    """The absolute path for a spec-declared relative path, or refuse it.

    Belt and braces over `_check_contained`: that one reads the string, this
    one resolves it and checks the answer is still under `root`, which is what
    catches a symlinked directory pointing out of the tree.
    """
    _check_contained(candidate, at)
    resolved = (root / candidate).resolve()
    if not resolved.is_relative_to(root.resolve()):
        raise SpecError(f"{at} resolves outside the repository ({resolved})")
    return resolved


# --- drafting ------------------------------------------------------------


def read_prd(path: Path, root: Path) -> str:
    """The PRD's text, bounded and confined to the repo.

    Its bytes travel to an endpoint, so it gets the rubric's rules: inside the
    repository, under a declared ceiling.
    """
    try:
        resolved = path.resolve()
        inside = resolved.is_relative_to(root.resolve())
    except OSError as exc:  # pragma: no cover - unreadable path
        raise SpecError(f"cannot read {path}: {exc}") from exc
    if not inside:
        raise SpecError(
            f"PRD {path} resolves outside the repository ({resolved}) — its "
            "contents would be sent to an endpoint, so it must be a file the "
            "repo itself holds"
        )
    if not resolved.is_file():
        raise SpecError(f"no PRD at {path}")

    raw = resolved.read_bytes()
    if len(raw) > MAX_PRD_BYTES:
        raise SpecError(
            f"PRD {path} is {len(raw)} bytes, over the {MAX_PRD_BYTES}-byte "
            "limit — these bytes travel"
        )
    text = raw.decode("utf-8", errors="replace").strip()
    if not text:
        raise SpecError(f"PRD {path} is empty — there is nothing to draft from")
    return text


def quote_intent(prd: str) -> str:
    """The human's own words, verbatim, for the artifact they will approve.

    Never the model's summary of them. If a drafter misread the PRD, the
    reader needs the PRD beside the criteria to notice.
    """
    # Control characters YAML cannot carry in a block scalar. A PRD holding
    # one would otherwise produce a spec file that will not load — and the
    # first thing anyone would do with it is approve it.
    quoted = "".join(
        ch for ch in prd if ch in "\t\n" or (ch >= " " and ch != "\x7f")
    )
    if len(quoted) <= MAX_INTENT_CHARS:
        return quoted
    return (
        quoted[:MAX_INTENT_CHARS]
        + f"\n\n[wringer: quoted the first {MAX_INTENT_CHARS} characters of "
        "the PRD; read the file itself for the rest]"
    )


def render_request(prd: str, model: str, max_output_tokens: int) -> dict:
    """The exact chat-completions body. Built from the PRD and nothing else."""
    user = (
        "# Product requirements\n\n"
        f"{prd}\n\n"
        "---\n\n"
        "## Your task\n"
        "Turn the requirements above into a build specification.\n\n"
        "Rules, in order of importance:\n"
        "1. **Never guess.** Anything you had to assume becomes an entry in "
        "`open_questions` instead. A question is better than a wrong "
        "criterion.\n"
        "2. **Every criterion must be checkable.** Prefer criteria a test or "
        "a lint can decide. Mark a criterion `\"human\": true` when only a "
        "person can judge it — taste, tone, or a trade-off.\n"
        "3. **Propose gates the repository could actually run** — its own "
        "test and lint commands. Propose none rather than inventing one.\n"
        "4. Split the work into tasks a single agent can finish. Give each an "
        "`objective`: one paragraph saying what done looks like.\n\n"
        "## Reply format\n"
        "Return ONLY a JSON object, no prose and no code fence:\n"
        "{\n"
        '  "title": "<one line>",\n'
        '  "open_questions": [{"id": "<slug>", "question": "<one line>", '
        '"required": true}],\n'
        '  "criteria": [{"id": "<slug>", "title": "<one line>", '
        '"guidance": "<how to check it>", "required": true, "human": false}],\n'
        '  "gates": [{"id": "<slug>", "run": "<shell command>"}],\n'
        '  "tasks": [{"id": "<slug>", "brief": "briefs/<slug>.md", '
        '"dir": ".", "objective": "<one paragraph>"}]\n'
        "}\n"
        "Slugs are letters, digits, '-' and '_'. At least one criterion must "
        "be `required`. At least one task."
    )
    return {
        "model": model,
        "max_tokens": max_output_tokens,
        "temperature": 0,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You turn product requirements into a build specification: "
                    "acceptance criteria, gates, and tasks. You never invent a "
                    "requirement — anything the document does not say becomes "
                    "an open question. Answer only with the requested JSON."
                ),
            },
            {"role": "user", "content": user},
        ],
    }


def parse_response(body: Any, prd: str) -> Spec:
    """Turn a model reply into a validated spec, or refuse it outright.

    Every field the model proposes goes through the same parser the file
    itself will face, so the caller either gets a spec that loads or an
    exception — never a half-formed document to write out and apologise for.

    `approved` is not read from the reply. There is no key here that could
    set it.
    """
    try:
        content = body["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError):
        raise SpecError(
            "the reply had no message content — nothing was drafted, and "
            "nothing was written"
        ) from None
    try:
        drafted = json.loads(_strip_fences(str(content)))
    except (ValueError, json.JSONDecodeError) as exc:
        raise SpecError(
            f"the reply was not the JSON object the request asked for ({exc}) "
            "— nothing was written"
        ) from exc
    if not isinstance(drafted, dict):
        raise SpecError("the reply was JSON but not an object — nothing was written")

    # Strict, like every other loader here, and loudest where it matters: a
    # reply carrying `approved` is a reply that tried to work the interlock,
    # and the honest answer to that is a refusal a human reads, not a silent
    # discard.
    unknown = sorted(
        set(drafted) - {"title", "open_questions", "criteria", "gates", "tasks"}
    )
    if unknown:
        raise SpecError(
            f"the reply carried keys the request did not ask for: "
            f"{', '.join(unknown)} — nothing was written"
        )

    return parse(
        {
            "schema_version": SCHEMA_VERSION,
            # Written here, not read from the reply. The interlock is a
            # constant in this expression; there is no branch that sets it.
            "approved": False,
            "title": drafted.get("title"),
            # The human's words, not the model's paraphrase of them.
            "intent": quote_intent(prd),
            "open_questions": drafted.get("open_questions") or [],
            "criteria": drafted.get("criteria"),
            "gates": drafted.get("gates") or [],
            "tasks": drafted.get("tasks"),
        },
        "the drafted spec",
    )


def _strip_fences(text: str) -> str:
    stripped = text.strip()
    if stripped.startswith("```"):
        lines = stripped.splitlines()
        lines = lines[1:-1] if len(lines) > 2 and lines[-1].startswith("```") \
            else lines[1:]
        return "\n".join(lines)
    return stripped


def render(spec: Spec) -> str:
    """The spec as the file a human reads and edits.

    Hand-rolled rather than `yaml.dump` because this document is a form: the
    interlock needs a comment beside it, and the questions need room to be
    answered in. A dumped mapping would be correct and unreadable.
    """
    lines = [
        f"# {SCHEMA_VERSION} — drafted by `wring spec`, approved by you.",
        "#",
        "# Nothing runs until 'approved' below says true, and only a person",
        "# can make it say that: there is no flag, and no --yes.",
        "",
        f"schema_version: {SCHEMA_VERSION}",
        f"approved: {str(spec.approved).lower()}"
        "        # <- the interlock. `wring plan` refuses while this is false.",
        f"title: {_scalar(spec.title)}",
        "",
        "# Your own words, quoted from the PRD. Check the criteria below",
        "# against this, not against what you meant to write.",
        # An explicit indentation indicator, because a PRD whose first line is
        # itself indented would otherwise set the block's indent for every
        # line after it and silently reflow the quote.
        "intent: |2",
    ]
    lines += [f"  {line}".rstrip() for line in spec.intent.splitlines()]

    lines += ["", "# Answer each question by writing an 'answer:' line under it,"]
    lines += ["# or delete the question. `wring plan` refuses while a required"]
    lines += ["# one is unanswered.", "open_questions:"]
    if not spec.questions:
        lines[-1] = "open_questions: []"
    for question in spec.questions:
        lines += [
            f"  - id: {question.id}",
            f"    question: {_scalar(question.question)}",
            f"    required: {str(question.required).lower()}",
            f"    answer: {_scalar(question.answer)}",
        ]

    lines += [
        "",
        "# The acceptance criteria — a wringer.rubric.v1 document, which is",
        "# what `wring judge` will weigh the finished change against.",
        "# 'human: true' means no judge may score it; a person must.",
        "criteria:",
    ]
    for criterion in spec.criteria:
        lines += [
            f"  - id: {criterion.id}",
            f"    title: {_scalar(criterion.title)}",
        ]
        if criterion.guidance:
            lines.append(f"    guidance: {_scalar(criterion.guidance)}")
        lines += [
            f"    required: {str(criterion.required).lower()}",
            f"    human: {str(criterion.human).lower()}",
        ]

    lines += [
        "",
        "# Proposed gates. `wring plan` prints these as a diff against",
        "# .wringer.yaml and stops — Wringer never installs a gate itself.",
        "gates:" if spec.gates else "gates: []",
    ]
    for gate in spec.gates:
        lines += [f"  - id: {gate.id}", f"    run: {_scalar(gate.run)}"]
        if gate.timeout != config.DEFAULT_TIMEOUT_SECONDS:
            lines.append(f"    timeout: {gate.timeout}")
        if gate.optional:
            lines.append("    optional: true")

    lines += [
        "",
        "# The build plan. `wring plan` turns these into tasks.jsonl and",
        "# writes each brief to the path named here.",
        "tasks:",
    ]
    for task in spec.tasks:
        lines += [
            f"  - id: {task.id}",
            f"    brief: {_scalar(task.brief)}",
            f"    dir: {_scalar(task.dir)}",
            f"    objective: {_scalar(task.objective)}",
        ]
    return "\n".join(lines) + "\n"


def _scalar(value: str) -> str:
    """One YAML scalar on one line, quoted by the emitter, never by guesswork.

    Double-quoted when the value contains a newline, because that is the only
    style that escapes one: this renderer builds the file line by line, and a
    scalar that decided to span three of them would land at an indentation
    nobody chose and change what the document says.
    """
    dumped = yaml.safe_dump(
        value,
        default_style='"' if "\n" in value else None,
        default_flow_style=True,
        allow_unicode=True,
        width=10**6,
    )
    return dumped.strip().removesuffix("\n...").strip()


